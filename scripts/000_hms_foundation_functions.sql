-- Призначення:
--   Ці функції є фундаментом для всіх бізнес-правил бази даних.
--   Вони нормалізують тексти, перевіряють email, автоматично
--   оновлюють timestamp та генерують унікальні номери документів.
--
-- Що зміниться після застосування:
--   1. Будь-яка таблиця, яка отримає тригер fn_set_updated_at(),
--      автоматично оновлюватиме поле updated_at при кожному UPDATE.
--   2. Функція fn_clean_text дозволить іншим тригерам нормалізувати текст.
--   3. Функція fn_is_valid_email забезпечить єдиний стандарт перевірки email.
--   4. Функція fn_generate_document_number зможе автоматично створювати
--      унікальні номери для бронювань, рахунків, заявок на обслуговування.
--
-- Зверніть увагу:
--   - Жодна таблиця ще не змінена. Це лише "інструменти".
--   - Функції не створюють жодних побічних ефектів на дані.
--   - Можна запускати безпечно навіть на production (якщо немає
--     однойменних функцій з іншою сигнатурою).
-- ============================================================

BEGIN;

-- ------------------------------------------------------------
-- 1. Функція автоматичного оновлення updated_at
-- ------------------------------------------------------------
-- Призначення: використовується в BEFORE UPDATE тригерах для
--              будь-якої таблиці, яка має колонку updated_at.
-- Поведінка: встановлює updated_at = поточний час (now()).
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_set_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at := now();
  RETURN NEW;
END;
$$;

-- ------------------------------------------------------------
-- 2. Функція нормалізації тексту
-- ------------------------------------------------------------
-- Призначення: очистити вхідний текст від зайвих пробілів,
--              замінити множинні пробіли на одинарні,
--              перетворити порожній рядок на NULL.
-- Використання: у тригерах BEFORE INSERT/UPDATE для полів,
--               які не мають права бути пустими.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_clean_text(p_text text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT NULLIF(btrim(regexp_replace(p_text, '\s+', ' ', 'g')), '');
$$;

-- ------------------------------------------------------------
-- 3. Функція перевірки формату email
-- ------------------------------------------------------------
-- Призначення: перевірити, чи рядок є валідною email-адресою.
-- Особливості: допускає NULL, регістронезалежна перевірка.
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_is_valid_email(p_email text)
RETURNS boolean
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT p_email IS NULL OR p_email ~* '^[A-Z0-9._%+\-]+@[A-Z0-9.\-]+\.[A-Z]{2,}$';
$$;

-- ------------------------------------------------------------
-- 4. Функція генерації унікального номера документа
-- ------------------------------------------------------------
-- Призначення: створює гарантовано унікальний текстовий ідентифікатор
--              для записів таблиці (reservation_number, folio_number,
--              request_number тощо).
--
-- Параметри:
--   p_prefix - текстовий префікс (напр. 'RES-', 'FOL-', 'MNT-')
--   p_table  - реєстраційний клас таблиці (напр. 'public.reservations'::regclass)
--   p_column - назва колонки, де має зберігатися унікальне значення
--
-- Формат номера: {PREFIX}{YYYYMMDD}-{8 випадкових HEX-символів}
-- Приклад: RES-20260525-A1B2C3D4
--
-- Алгоритм:
--   1. Генерує кандидата (префікс + дата + 8 символів від UUID)
--   2. Динамічно перевіряє, чи існує таке значення в таблиці
--   3. Якщо існує (колізія вкрай малоймовірна, але можлива), повторює
--   4. Повертає унікальне значення
--
-- Використання у тригерах (BEFORE INSERT):
--   IF NEW.reservation_number IS NULL THEN
--       NEW.reservation_number := fn_generate_document_number('RES-', TG_RELID, 'reservation_number');
--   END IF;
-- ------------------------------------------------------------
CREATE OR REPLACE FUNCTION public.fn_generate_document_number(
  p_prefix text,
  p_table regclass,
  p_column text
)
RETURNS text
LANGUAGE plpgsql
AS $$
DECLARE
  v_candidate text;
  v_exists boolean;
  v_sql text;
BEGIN
  LOOP
    -- Формуємо кандидата: префікс + дата (YYYYMMDD) + 8 випадкових символів
    v_candidate := p_prefix || to_char(now(), 'YYYYMMDD') || '-' || upper(substr(replace(gen_random_uuid()::text, '-', ''), 1, 8));
    -- Динамічний запит на перевірку унікальності
    v_sql := format('SELECT EXISTS (SELECT 1 FROM %s WHERE %I = $1)', p_table, p_column);
    EXECUTE v_sql INTO v_exists USING v_candidate;
    EXIT WHEN NOT v_exists;  -- Якщо унікальний – виходимо з циклу
  END LOOP;

  RETURN v_candidate;
END;
$$;

COMMIT;

